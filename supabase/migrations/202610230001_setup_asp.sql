-- Acceso CRUD limitado a administradores ASP autorizados en asp_admins.
create table if not exists public.asp_questions (
  id integer generated by default as identity primary key,
  question text not null,
  options jsonb not null check (jsonb_typeof(options) = 'array' and jsonb_array_length(options) = 4),
  answer text not null check (answer in ('a','b','c','d')),
  explanation text not null default ''
);
alter table public.asp_questions enable row level security;
revoke all on public.asp_questions from anon, authenticated;
grant all on public.asp_questions to service_role;

create table if not exists public.asp_admins (
  user_id uuid primary key references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);
alter table public.asp_admins enable row level security;
revoke all on public.asp_admins from public, anon, authenticated;

create or replace function public.is_asp_admin()
returns boolean language sql stable security definer set search_path = pg_catalog, public
as $$ select exists (select 1 from public.asp_admins where user_id = auth.uid()); $$;
revoke all on function public.is_asp_admin() from public, anon;
grant execute on function public.is_asp_admin() to authenticated;
grant select, insert, update, delete on public.asp_questions to authenticated;

do $$
declare seq text;
begin
  seq := pg_get_serial_sequence('public.asp_questions','id');
  if seq is not null then execute format('grant usage, select on sequence %s to authenticated', seq); end if;
end $$;

drop policy if exists "ASP admins can manage questions" on public.asp_questions;
create policy "ASP admins can manage questions" on public.asp_questions
for all to authenticated using (public.is_asp_admin()) with check (public.is_asp_admin());
